// AFDKO feature-file (.fea) export — the same ligatures, kerning and mark positioning the font itself carries,
// so the font can be opened in FontCreator / Glyphs / fontmake / fonttools. Pure function of the font model.
import { resolveLigatures } from './gsubWriter.js';
import { computeKerning, computeMarkAttachments, isMarkCode, isSpacingSign } from './gposWriter.js';

const nm = (glyphs, gid) => glyphs[gid].name;

export function buildFea(model) {
  const g = model.glyphs;
  const L = [];
  L.push(`# ${model.familyName} — generated by KRTD Font Craft Ultra`, '', 'languagesystem DFLT dflt;', 'languagesystem sinh dflt;', '');

  const ligs = resolveLigatures(g);
  if (ligs.length) {
    L.push('feature ccmp {');
    ligs.forEach((l) => L.push(`  sub ${l.components.map((c) => nm(g, c)).join(' ')} by ${nm(g, l.glyph)};`));
    L.push('} ccmp;', '', 'feature liga {');
    ligs.forEach((l) => L.push(`  sub ${l.components.map((c) => nm(g, c)).join(' ')} by ${nm(g, l.glyph)};`));
    L.push('} liga;', '');
  }

  const pairs = computeKerning(g);
  if (pairs.length) {
    L.push('feature kern {');
    pairs.slice().sort((a, b) => a.left - b.left || a.right - b.right)
      .forEach((p) => L.push(`  pos ${nm(g, p.left)} ${nm(g, p.right)} ${p.value};`));
    L.push('} kern;', '');
  }

  const mk = computeMarkAttachments(g);
  if (mk) {
    mk.marks.forEach((m) => L.push(`markClass ${nm(g, m.gid)} <anchor ${m.ax} ${m.ay}> @MC_${m.cls};`));
    L.push('');
    ['abvm', 'blwm', 'mark'].forEach((tag) => {
      L.push(`feature ${tag} {`);
      mk.marks.forEach((m) => {
        const above = m.above;
        if ((tag === 'abvm' && !above) || (tag === 'blwm' && above)) return;
        mk.bases.forEach((b) => L.push(`  pos base ${nm(g, b.gid)} <anchor ${b.anchors[m.cls].x} ${b.anchors[m.cls].y}> mark @MC_${m.cls};`));
      });
      L.push(`} ${tag};`, '');
    });
  }

  const marks = g.filter((x) => isMarkCode(x.unicode)).map((x) => x.name);
  const ligNames = g.filter((x) => x.sequence).map((x) => x.name);
  const bases = g.filter((x, i) => i > 0 && x.unicode !== 32 && x.contours.length && !isMarkCode(x.unicode) && !x.sequence && !isSpacingSign(x.unicode)).map((x) => x.name);
  L.push('table GDEF {',
    `  GlyphClassDef [${bases.join(' ')}], [${ligNames.join(' ')}], [${marks.join(' ')}], ;`,
    '} GDEF;', '');
  return L.join('\n');
}
